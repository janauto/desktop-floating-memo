/** 随机取一条语录，避免与上一条重复 */
export function getRandomQuote(): Quote {
  let idx: number
  do {
    idx = Math.floor(Math.random() * QUOTES.length)
  } while (idx === lastIndex && QUOTES.length > 1)
  lastIndex = idx
  return QUOTES[idx]
}
